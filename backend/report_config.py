def _adjust(section: dict, required: dict | None = None, labels: dict | None = None) -> dict:
    """Copy of a shared section with some fields' mandatory flag / label changed for the VEE report types."""
    return {**section, "fields": [{**f, **({"required": required[f["key"]]} if f["key"] in (required or {}) else {}),
                                   **({"label": labels[f["key"]]} if f["key"] in (labels or {}) else {})}
                                  for f in section["fields"]]}


